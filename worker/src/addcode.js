export function parseAddCode(value) {
  const code = String(value ?? "").trim();
  if (!/^\d{5}$/.test(code)) return { ADD_READER: "", ADD_FORM: "", ADD_CONTENT: "" };
  return {
    ADD_READER: READER[code[0]] ?? "",
    ADD_FORM: FORM[code[1]] ?? "",
    ADD_CONTENT: CONTENT[code.slice(2, 4)] ?? "",
  };
}

// SUBJECT 는 내용분류 대분류 숫자 한 자리로 온다 → 이름. 그 밖의 값은 그대로 둔다
export function subjectName(value) {
  const s = String(value ?? "").trim();
  return /^\d$/.test(s) ? MAIN_CLASS[s] : s;
}
